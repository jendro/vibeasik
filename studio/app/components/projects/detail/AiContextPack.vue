<script setup lang="ts">
import type { FastScanResult, Project, ProjectComponent } from '~/types'

const props = defineProps<{
  comp: ProjectComponent
  project: Project
  scanResult: FastScanResult
}>()

const toast = useToast()
const copied = ref(false)

// Ringkasan konteks komponen (format XML ala Repomix) untuk ditempel ke prompt AI
const contextPack = computed(() => {
  const c = props.comp
  const s = props.scanResult
  const routes = s.routes || []
  const envKeys = s.extracted_env?.environment_keys || []

  return `<!-- =================================================================
     CODEBASE CONTEXT PACK
     Generated by vibeasik
     Project: ${props.project.name} | Component: ${c.name}
     Role: ${c.role} | Language: ${c.language} | Framework: ${c.framework}
     Port: ${c.port} | Dev Command: ${c.dev_command || '-'}
================================================================= -->

<codebase_summary>
  <component_name>${c.name}</component_name>
  <role>${c.role}</role>
  <path>${c.absolute_path}</path>
  <framework>${s.architecture?.framework || c.framework}</framework>
  <design_pattern>${s.architecture?.design_pattern || '-'}</design_pattern>
  <database_engine>${s.extracted_env?.database_type || 'None'}</database_engine>
  <orm_driver>${s.extracted_env?.orm_driver || 'None'}</orm_driver>
  <total_routes>${routes.length}</total_routes>
  <auth_methods>${(s.extracted_env?.auth_methods || []).join(', ') || 'None'}</auth_methods>
</codebase_summary>

<directory_tree>
${s.directory_tree || '(Run Fast Scan to extract tree)'}
</directory_tree>

<api_routes>
${routes.map(r => `  - [${r.method}] ${r.path} -> ${r.handler} (${r.middleware || 'Public'}) : ${r.description}`).join('\n')}
</api_routes>

<sanitized_environment_keys>
${envKeys.map(k => `  - ${k.key} : ${k.purpose} (Required: ${k.required}, Secret: ${k.is_secret}) [Example: ${k.safe_example}]`).join('\n')}
</sanitized_environment_keys>

<how_to_run>
  Dev Command: ${s.how_to_run?.dev_command || c.dev_command || '-'}
  Build Command: ${s.how_to_run?.build_command || c.build_command || '-'}
  Install Command: ${s.how_to_run?.install_command || '-'}
</how_to_run>
`
})

const copyPack = async () => {
  try {
    await navigator.clipboard.writeText(contextPack.value)
    copied.value = true
    setTimeout(() => {
      copied.value = false
    }, 3000)
    toast.add({
      title: 'Disalin ke Clipboard',
      description: 'AI Context Pack siap ditempel ke asisten AI.',
      icon: 'i-lucide-clipboard-check',
      color: 'neutral'
    })
  } catch {
    toast.add({
      title: 'Gagal Menyalin',
      description: 'Gagal menyalin ke clipboard.',
      icon: 'i-lucide-alert-circle',
      color: 'error'
    })
  }
}
</script>

<template>
  <div class="p-4 rounded-xl border border-neutral-200 dark:border-white/10 bg-white dark:bg-slate-900/40 shadow-2xs space-y-3">
    <div class="flex flex-col sm:flex-row sm:items-center justify-between gap-3">
      <div>
        <h3 class="text-sm font-bold text-neutral-900 dark:text-white flex items-center gap-2">
          <UIcon name="i-lucide-file-text" class="w-4 h-4 text-amber-500" />
          <span>AI Context Pack</span>
        </h3>
        <p class="text-xs text-neutral-500 mt-0.5">
          Ringkasan komponen, rute, pohon folder, dan env key (sudah disanitasi) dalam satu teks — tinggal salin dan tempel ke Claude Code, Cursor, Antigravity, atau ChatGPT.
        </p>
      </div>

      <UButton
        icon="i-lucide-copy"
        color="primary"
        variant="solid"
        size="xs"
        @click="copyPack"
      >
        {{ copied ? 'Disalin!' : 'Salin Context Pack' }}
      </UButton>
    </div>

    <div class="p-4 rounded-xl bg-neutral-900 border border-neutral-800 text-neutral-200 font-mono text-xs overflow-x-auto max-h-96 leading-relaxed">
      <pre class="whitespace-pre text-neutral-300">{{ contextPack }}</pre>
    </div>
  </div>
</template>
